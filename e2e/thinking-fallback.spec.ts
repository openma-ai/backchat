import { expect, test } from "./fixtures";
import { injectEvent, injectSession } from "./helpers";

test("unresolved text and completed tools keep exactly one live indicator", async ({ page, app, capture }) => {
  await app.evaluate(({ ipcMain }) => { ipcMain.removeHandler("session:start"); ipcMain.handle("session:start", () => ({})); });
  const id = await injectSession(page, { sessionId: "thinking-tail" });
  const send = (event: Record<string, unknown>) => injectEvent(page, { type: "session.event", session_id: id, turn_id: "thinking-turn", event });
  await send({ sessionUpdate: "agent_message_chunk", content: { type: "text", text: "An interim progress message" } });
  await injectEvent(page, { type: "session.queue_update", session_id: id, mode: "single", active_turn_id: "thinking-turn", queued: [] });
  const turn = page.locator('[data-turn-id="thinking-turn"]');
  await expect(turn.locator('[data-thinking-fallback]')).toHaveCount(1);
  await capture("thinking-after-commentary.png");
  await send({ sessionUpdate: "tool_call", toolCallId: "read", title: "Read file", kind: "read", status: "in_progress" });
  await expect(turn.locator('[data-thinking-fallback]')).toHaveCount(0);
  await send({ sessionUpdate: "tool_call_update", toolCallId: "read", status: "completed" });
  await expect(turn.locator('[data-thinking-fallback]')).toHaveCount(1);
  expect(await turn.locator('[data-thinking-fallback]').evaluate(el=>!!el.closest('[data-collapsible-event-count]'))).toBe(true);
  await send({sessionUpdate:"tool_call",toolCallId:"second",title:"Second command",kind:"execute",status:"completed"});
  await send({sessionUpdate:"session_info_update",_meta:{codex:{threadStatus:{type:"active"}}}});
  const fallback=turn.locator('[data-thinking-fallback]');
  await expect(fallback).toHaveCount(1);
  expect(await fallback.evaluate(el=>!!el.closest('[data-collapsible-event-count]'))).toBe(true);
  const group=fallback.locator('xpath=ancestor::*[@data-collapsible-event-count][1]');
  const trigger=group.locator('[data-chat-activity-disclosure-trigger]').first();
  await expect(trigger).toContainText('Thinking');
  await expect(trigger.locator('.shimmer-text')).toHaveCount(1);
  await trigger.click();
  await expect(trigger).toHaveAttribute('aria-expanded','true');
  await expect(fallback).toHaveCount(1);
  await capture('thinking-in-process-header.png');
  await send({sessionUpdate:"tool_call",toolCallId:"third",title:"Third command",kind:"execute",status:"in_progress"});
  await expect(turn.locator('[data-thinking-fallback]')).toHaveCount(0);
  await send({sessionUpdate:"tool_call_update",toolCallId:"third",status:"completed"});
  await expect(turn.locator('[data-thinking-fallback]')).toHaveCount(1);
  await send({ sessionUpdate: "agent_thought_chunk", content: { type: "text", text: "Actual thought activity" } });
  await expect(turn.locator('[data-thinking-fallback]')).toHaveCount(0);
  await expect(turn.locator('[data-thought-live="true"]')).toHaveCount(1);
  await expect(turn.locator('[data-thought-live="true"] .shimmer-text')).toHaveCount(1);
  await page.emulateMedia({reducedMotion:'no-preference'});
  await page.addStyleTag({content:'.shimmer-text { animation-duration: 1.6s !important; }'});
  const shimmer=turn.locator('[data-thought-live="true"] .shimmer-text');
  await expect(shimmer).toHaveCSS('animation-name','shimmer-text-sweep');
  const positions=await shimmer.evaluate(async el=>{
    const animations=el.getAnimations();
    for(const animation of animations){animation.pause();animation.currentTime=0;}
    const start=getComputedStyle(el).backgroundPosition;
    for(const animation of animations)animation.currentTime=800;
    const middle=getComputedStyle(el).backgroundPosition;
    return {start,middle};
  });
  expect(positions.start).not.toBe(positions.middle);
  await page.emulateMedia({reducedMotion:'reduce'});
  await expect(shimmer).toHaveCSS('animation-name','none');
  await capture("thinking-native-activity.png");
  await injectEvent(page, { type: "session.complete", session_id: id, turn_id: "thinking-turn", stop_reason: "end_turn" });
  await expect(turn.locator('[data-thinking-fallback]')).toHaveCount(0);
  await injectEvent(page,{type:'session.event',session_id:id,turn_id:'',event:{sessionUpdate:'tool_call_update',toolCallId:'third',status:'completed'}});
  await expect(page.locator('[data-turn-id=""]')).toHaveCount(0);
  await expect(turn).toHaveAttribute("data-session-turn-status", "complete");
  await injectEvent(page, { type: "session.queue_update", session_id: id, mode: "single", active_turn_id: "thinking-turn", queued: [] });
  await expect(turn).toHaveAttribute("data-session-turn-status", "complete");
  await expect(page.locator(`.sidebar-grid-row[data-session-id="${id}"] [data-sidebar-activity="running"]`)).toHaveCount(0);
  await expect(page.getByRole("button", { name: "Stop", exact: true })).toHaveCount(0);
});
