import { describe, expect, it, vi } from "vitest";
import { createRepositoryImageCache, customRepositoryImage, readRepositoryImage } from "./repository-image.js";

const image = "https://repository-images.githubusercontent.com/123/custom.png";
describe("repository custom artwork", () => {
  it("never uses an autogenerated repository card", () => {
    expect(customRepositoryImage({ usesCustomOpenGraphImage: false, openGraphImageUrl: image })).toBeNull();
    expect(customRepositoryImage({ openGraphImageUrl: image })).toBeNull();
    expect(customRepositoryImage({ usesCustomOpenGraphImage: true, openGraphImageUrl: image })).toBe(image);
  });
  it("prefers custom artwork and falls back to the organization or user avatar", () => {
    const avatar = "https://avatars.githubusercontent.com/u/123?s=64";
    const owner = { avatarUrl: avatar };
    expect(customRepositoryImage({ usesCustomOpenGraphImage: true, openGraphImageUrl: image, owner })).toBe(image);
    expect(customRepositoryImage({ usesCustomOpenGraphImage: false, openGraphImageUrl: image, owner })).toBe(avatar);
    expect(customRepositoryImage({ usesCustomOpenGraphImage: true, openGraphImageUrl: "bad-url", owner })).toBe(avatar);
    expect(customRepositoryImage({ owner })).toBe(avatar);
  });
  it("rejects non-image origins and credential-bearing URLs", () => {
    for (const url of ["https://example.com/image.png", "https://githubusercontent.com.evil.test/a", "https://user:pass@repository-images.githubusercontent.com/a", "file:///tmp/a"])
      expect(customRepositoryImage({ usesCustomOpenGraphImage: true, openGraphImageUrl: url })).toBeNull();
  });
  it.each(["git@github.com:team/project.git", "https://github.com/team/project.git"])("resolves %s through authenticated repo metadata", async remote => {
    const result = await readRepositoryImage("/repo", async (cmd, args) => {
      if (cmd === "git") return remote;
      expect(args).toContain("owner=team");
      expect(args).toContain("name=project");
      expect(args.join(" ")).toContain("owner{avatarUrl(size:64)}");
      return JSON.stringify({ data: { repository: { usesCustomOpenGraphImage: true, openGraphImageUrl: image } } });
    });
    expect(result).toBe(image);
  });
  it("falls back to the owner avatar when gh is missing, timed out or offline", async () => {
    const result = await readRepositoryImage("/repo", async (cmd) => {
      if (cmd === "git") return "git@github.com:team/project.git";
      throw new Error("gh: command not found");
    });
    expect(result).toBe("https://avatars.githubusercontent.com/team?s=64");
  });
  it("falls back to the owner avatar when the repository metadata has no image", async () => {
    const result = await readRepositoryImage("/repo", async (cmd) => {
      if (cmd === "git") return "git@github.com:team/project.git";
      return JSON.stringify({ data: { repository: { usesCustomOpenGraphImage: false, owner: { avatarUrl: null } } } });
    });
    expect(result).toBe("https://avatars.githubusercontent.com/team?s=64");
  });
  it("prefers the owner avatar reported by gh over the constructed one", async () => {
    const reported = "https://avatars.githubusercontent.com/u/123?s=64&v=4";
    const result = await readRepositoryImage("/repo", async (cmd) => {
      if (cmd === "git") return "git@github.com:team/project.git";
      return JSON.stringify({ data: { repository: { usesCustomOpenGraphImage: false, owner: { avatarUrl: reported } } } });
    });
    expect(result).toBe(reported);
  });
  it.each([
    "https://github.com/team/project.git/",
    "https://github.com/team/project/",
    "git@github.com:team/project.git/",
  ])("resolves %s with a trailing slash", async remote => {
    const result = await readRepositoryImage("/repo", async (cmd) => {
      if (cmd === "git") return remote;
      throw new Error("gh unavailable");
    });
    expect(result).toBe("https://avatars.githubusercontent.com/team?s=64");
  });
  it("keeps the letter tile for a remote that is not on GitHub", async () => {
    expect(await readRepositoryImage("/repo", async (cmd) => {
      if (cmd === "git") return "git@gitlab.com:team/project.git";
      throw new Error("gh unavailable");
    })).toBeNull();
  });
  it("returns no image when the remote cannot be read", async () => {
    expect(await readRepositoryImage("/repo", async () => { throw new Error("unavailable"); })).toBeNull();
  });
});

describe("main-owned repository image cache", () => {
  const avatar = "https://avatars.githubusercontent.com/u/1?s=64";
  const newer = "https://avatars.githubusercontent.com/u/2?s=64";

  async function tempFile(): Promise<string> {
    const { mkdtemp } = await import("node:fs/promises");
    const { tmpdir } = await import("node:os");
    const { join } = await import("node:path");
    return join(await mkdtemp(join(tmpdir(), "backchat-repo-image-")), "repository-images.json");
  }

  it("serves a persisted image after restart without calling gh", async () => {
    const file = await tempFile();
    let now = 1_000;
    const first = createRepositoryImageCache({ file, read: async () => avatar, now: () => now });
    expect(await first.get("/repo")).toBe(avatar);
    await first.flush();

    const read = vi.fn(async () => newer);
    const second = createRepositoryImageCache({ file, read, now: () => now });
    expect(await second.get("/repo")).toBe(avatar);
    expect(read).not.toHaveBeenCalled();
  });

  it("refreshes a stale image in the background and keeps the old one on failure", async () => {
    const file = await tempFile();
    let now = 0;
    let fail = false;
    const read = vi.fn(async () => {
      if (fail) throw new Error("gh timed out");
      return read.mock.calls.length <= 1 ? avatar : newer;
    });
    const cache = createRepositoryImageCache({
      file, read, now: () => now, refreshAfterMs: 100, retryAfterFailureMs: 1_000,
    });
    expect(await cache.get("/repo")).toBe(avatar);

    now = 500;
    fail = true;
    // Stale: answer immediately with the last good value, refresh behind.
    expect(await cache.get("/repo")).toBe(avatar);
    await cache.idle();
    expect(read).toHaveBeenCalledTimes(2);
    // The failure kept the good image and does not retry on every read.
    expect(await cache.get("/repo")).toBe(avatar);
    await cache.idle();
    expect(read).toHaveBeenCalledTimes(2);

    fail = false;
    now = 1_600;
    await cache.get("/repo");
    await cache.idle();
    expect(read).toHaveBeenCalledTimes(3);
    expect(await cache.get("/repo")).toBe(newer);
  });

  it("collapses concurrent first reads into one gh call", async () => {
    const read = vi.fn(async () => avatar);
    const cache = createRepositoryImageCache({ file: await tempFile(), read, now: () => 0 });
    const results = await Promise.all([cache.get("/repo"), cache.get("/repo"), cache.get("/repo")]);
    expect(results).toEqual([avatar, avatar, avatar]);
    expect(read).toHaveBeenCalledTimes(1);
  });

  it("keeps a persisted owner avatar across restarts", async () => {
    const file = await tempFile();
    const ownerAvatar = "https://avatars.githubusercontent.com/team?s=64";
    const first = createRepositoryImageCache({ file, read: async () => ownerAvatar, now: () => 1_000 });
    expect(await first.get("/repo")).toBe(ownerAvatar);
    await first.flush();

    // The renderer reads from disk with an infinite stale time, so the
    // fallback must survive a reload without another `gh` call.
    const read = vi.fn(async () => null);
    const second = createRepositoryImageCache({ file, read, now: () => 1_000 });
    expect(await second.get("/repo")).toBe(ownerAvatar);
    expect(read).not.toHaveBeenCalled();
  });
});
